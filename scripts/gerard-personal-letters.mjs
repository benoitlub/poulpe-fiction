import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const WEEK_MS = 7 * 24 * 60 * 60 * 1000;
const RECENT_MS = 4 * 24 * 60 * 60 * 1000;
const CONTRACT = "gerard-personal-letters-v1";
const normalize = (x) => x && typeof x === "object" && !Array.isArray(x) ? x : {};
const isDate = (s) => typeof s === "string" && Number.isFinite(Date.parse(s));
const asArray = (x) => Array.isArray(x) ? x : [];

/**
 * Produces at most one evidence-grounded, owner-only letter in any rolling week.
 * Absence of a fresh noteworthy harvest is a valid result: silence.
 * This function never sends email, signs into Google or requires a reply.
 */
export function proposeGerardLetter({ state, harvests, existing, now = new Date() }) {
  const archive = normalize(existing);
  const letters = asArray(archive.letters).filter((x) => x && typeof x.id === "string").slice(-51);
  const base = { contract: CONTRACT, sendingEnabled: false, audience: "owner-only", letters };
  const clock = now instanceof Date ? now.getTime() : Date.parse(now);
  if (!Number.isFinite(clock)) return { ...base, created: false };
  const mostRecent = letters.reduce((max, x) => isDate(x.createdAt) ? Math.max(max, Date.parse(x.createdAt)) : max, -Infinity);
  if (clock - mostRecent < WEEK_MS) return { ...base, created: false };

  const harvestRecords = asArray(normalize(harvests).harvests);
  const seen = new Set(letters.map((x) => x.subjectKey).filter(Boolean));
  const achievements = asArray(normalize(state).learningHistory).filter((x) =>
    x?.decision === "harvest-produced" && x?.outcome === "ok" &&
    typeof x.operationId === "string" && isDate(x.at) &&
    clock >= Date.parse(x.at) && clock - Date.parse(x.at) <= RECENT_MS
  ).reverse();
  for (const event of achievements) {
    const harvest = harvestRecords.find((x) =>
      x?.harvestId === `${event.operationId}-harvest` &&
      x?.state !== "composted" &&
      typeof x.title === "string" && x.title.trim().length > 0 &&
      x.title.length <= 140 &&
      typeof x.content === "string" &&
      !/mode mock actif|simulation|placeholder/i.test(x.content)
    );
    if (!harvest) continue;
    const subjectKey = `${harvest.seedId || event.seedId}:${harvest.title.toLocaleLowerCase("fr").trim()}`;
    if (seen.has(subjectKey)) continue;
    const title = harvest.title.trim();
    const date = new Date(event.at).toLocaleDateString("fr-FR", { timeZone: "UTC", day: "numeric", month: "long" });
    const letter = {
      id: `gerard-letter-${event.operationId}`,
      createdAt: new Date(clock).toISOString(),
      source: { operationId: event.operationId, harvestId: harvest.harvestId, observedAt: event.at },
      subjectKey,
      title: `Une nouvelle pousse : ${title}`,
      body: `Salut Benoît,\n\nJe voulais te laisser un mot depuis le jardin. Le ${date}, une récolte intitulée « ${title} » a été enregistrée dans la parcelle ${harvest.parcelId || event.parcelId || "du jardin"}. C'est une chose concrète que j'ai trouvée dans mes traces, pas une promesse de vente ni de publication.\n\nJe la garde en mémoire pour la suite. Rien à faire de ton côté, et aucune obligation de répondre.\n\nGérard 🐙`,
      delivery: { status: "gmail-not-connected", sentAt: null, provider: "gmail", recipient: "owner-only" },
      evidence: "Autogenerated from verified local cycle and harvest records; no LLM inference."
    };
    return { ...base, letters: [...letters, letter].slice(-52), created: true };
  }
  return { ...base, created: false };
}

async function readJson(file, fallback) {
  try { return JSON.parse(await readFile(file, "utf8")); }
  catch (error) {
    if (error?.code === "ENOENT") return fallback;
    throw error; // Fail closed; never overwrite a corrupted archive.
  }
}
async function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const file = path.join(root, "garden", "gerard-personal-letters.json");
  const [state, harvests, archive] = await Promise.all([
    readJson(path.join(root, "garden", "gerard-state.json"), {}),
    readJson(path.join(root, "garden", "harvests.json"), {}),
    readJson(file, { letters: [] })
  ]);
  const result = proposeGerardLetter({ state, harvests, existing: archive });
  if (!result.created) { console.log("No personal letter warranted this cycle."); return; }
  const { created, ...persisted } = result;
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, JSON.stringify(persisted, null, 2) + "\n");
  console.log("One personal letter archived for the Banc; Gmail sending remains disabled.");
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => { console.error(error); process.exitCode = 1; });
}
